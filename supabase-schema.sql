-- Skema awal Supabase (review dan sesuaikan sebelum produksi)
create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  role text not null default 'visitor' check (role in ('visitor','admin')),
  created_at timestamptz default now()
);

create table public.destinations (
  id bigint generated by default as identity primary key,
  name text not null,
  area text,
  category text,
  description text,
  image_url text,
  active boolean not null default true,
  created_at timestamptz default now()
);

create table public.bookings (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id),
  destination_id bigint not null references public.destinations(id),
  visit_date date not null,
  quantity int not null check (quantity between 1 and 20),
  visitor_name text not null,
  status text not null default 'pending' check (status in ('pending','paid','cancelled','refunded')),
  created_at timestamptz default now()
);

alter table public.profiles enable row level security;
alter table public.destinations enable row level security;
alter table public.bookings enable row level security;

-- Public can read active destinations.
create policy "public read active destinations" on public.destinations
for select using (active = true);

-- Visitors can read and create only their own bookings.
create policy "read own bookings" on public.bookings
for select to authenticated using (auth.uid() = user_id);
create policy "create own bookings" on public.bookings
for insert to authenticated with check (auth.uid() = user_id);

-- Profiles: users can read/update only own profile.
create policy "read own profile" on public.profiles
for select to authenticated using (auth.uid() = id);
create policy "update own profile" on public.profiles
for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

